#!/usr/bin/env python3
"""Check freshly generated repositories against their owned manifest and scope.

This is a smoke-test boundary, not a validator for user-edited repositories.
It intentionally fails when unexpected files are present in a fresh output.
"""
import hashlib
import json
from pathlib import Path
import re
import sys

NON_TEMPLATE_MARKER = re.compile(r"\bUNREUSABLE_PROJECT_CONTENT\b")
VIEWER_TOKENS = re.compile(r"\{\{(?:DOCUMENT_LANGUAGE|PROJECT_NAME_HTML|PROJECT_DESCRIPTION_HTML|PROJECT_NAME_JSON|SITE_LOADING_HTML|SITE_SEARCH_PLACEHOLDER_JSON)\}\}")
OLD_SOURCE_ROOTS = {
    "business", "technical", "milestones", "catalog", "src", "tests", "schemas", "shared",
}
UNWANTED_ASSET_EXTENSIONS = {".js", ".css", ".map", ".mjs", ".cjs", ".ts", ".tsx"}
MAINTAINER_ONLY_PREFIXES = ("docs/audit/", "docs/legacy/")
EPHEMERAL_INTAKE = {
    "bootstrap.md",
    ".agents/bootstrap/questionnaire.md",
    ".agents/bootstrap/finish-checklist.md",
    ".agents/skills/project-intake/SKILL.md",
}


def check(root: Path) -> list[str]:
    errors: list[str] = []
    config_path = root / "docs.config.json"
    if not config_path.is_file():
        return [f"{root}: missing docs.config.json"]

    try:
        config = json.loads(config_path.read_text(encoding="utf-8"))
        managed = config["GeneratedFiles"]
        hashes = config["GeneratedHashes"]
        project_name = config["Name"]
        language = config.get("Language") or "en"
        site = config["Site"]
    except (ValueError, KeyError, TypeError) as exc:
        return [f"{root}: invalid configuration: {exc}"]

    if not isinstance(managed, list) or not isinstance(hashes, dict):
        return [f"{root}: invalid managed-file manifest shape"]

    owned = set(managed)
    if len(owned) != len(managed) or owned != set(hashes):
        errors.append(f"{root}: manifest paths and hashes disagree")

    actual = {
        p.relative_to(root).as_posix()
        for p in root.rglob("*")
        if p.is_file()
    }
    expected = owned | {"docs.config.json"}
    for path in sorted(expected - actual):
        errors.append(f"{root}: missing owned file {path}")
    for path in sorted(actual - expected - EPHEMERAL_INTAKE):
        errors.append(f"{root}: unexpected file in fresh output {path}")
    # A fresh init must ship the temporary intake pack; once it is complete,
    # these files may be removed independently of the manifest.
    for path in sorted(EPHEMERAL_INTAKE - actual):
        errors.append(f"{root}: missing fresh stage-two intake file {path}")

    for path in sorted(actual):
        rel = Path(path)
        if path.split("/")[0] in OLD_SOURCE_ROOTS:
            errors.append(f"{root}: predecessor/generator tree included: {path}")
        if path.startswith(MAINTAINER_ONLY_PREFIXES):
            errors.append(f"{root}: maintainer-only historical docs included: {path}")
        if rel.suffix.lower() in UNWANTED_ASSET_EXTENSIONS:
            errors.append(f"{root}: unexpected generated asset: {path}")
        if rel.suffix.lower() == ".html" and path != "index.html":
            errors.append(f"{root}: unexpected generated HTML page: {path}")
        if path == "docs.config.json":
            continue
        try:
            data = (root / path).read_bytes()
            content = data.decode("utf-8")
        except UnicodeDecodeError:
            errors.append(f"{root}: non-text file in Markdown-first output: {path}")
            continue
        match = NON_TEMPLATE_MARKER.search(content)
        if match:
            errors.append(f"{root}: non-template content marker {match.group(0)!r} in {path}")
        if "{{PROJECT_" in content:
            errors.append(f"{root}: unresolved project placeholder in {path}")
        if path in hashes and hashlib.sha256(data).hexdigest() != hashes[path]:
            errors.append(f"{root}: newly generated bytes differ from owned fingerprint: {path}")

    if site == "docsify":
        if "index.html" not in owned:
            errors.append(f"{root}: Docsify configured without its index.html shell")
        elif (root / "index.html").is_file():
            html = (root / "index.html").read_text(encoding="utf-8")
            if VIEWER_TOKENS.search(html):
                errors.append(f"{root}: unresolved Docsify template marker")
            if f'<html lang="{language}">' not in html:
                errors.append(f"{root}: Docsify HTML lang does not match manifest language {language!r}")
            search_label = "Поиск по документации" if language == "ru" else "Search documentation"
            search_token = re.search(r'placeholder:\s*("(?:\\.|[^"\\])*")', html)
            try:
                decoded_search = json.loads(search_token.group(1)) if search_token else None
            except ValueError:
                decoded_search = None
            if decoded_search != search_label:
                errors.append(f"{root}: Docsify search placeholder is not localized for {language!r}")
    elif site == "none":
        if "index.html" in actual:
            errors.append(f"{root}: HTML viewer leaked into headless output")
    else:
        errors.append(f"{root}: unsupported site mode {site!r}")

    for required in ("README.md", "AGENTS.md", "llms.txt", "docs/index.md", "docs/catalog.md"):
        if required not in actual:
            errors.append(f"{root}: missing agent/author entrypoint {required}")

    if isinstance(project_name, str) and (root / "README.md").is_file():
        if f"# {project_name}\n" not in (root / "README.md").read_text(encoding="utf-8"):
            errors.append(f"{root}: project name not rendered into README")
    return errors


def main() -> int:
    if len(sys.argv) < 2:
        print("Usage: generated_output_hygiene.py OUTPUT [OUTPUT ...]", file=sys.stderr)
        return 2
    failures: list[str] = []
    for name in sys.argv[1:]:
        folder = Path(name).resolve()
        if not folder.is_dir():
            failures.append(f"{name}: missing generated directory")
        else:
            failures.extend(check(folder))
    for error in failures:
        print("ERROR:", error, file=sys.stderr)
    print(f"Generated output hygiene: {len(sys.argv) - 1} projects checked; {len(failures)} findings.")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
